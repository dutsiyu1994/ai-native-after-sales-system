-- 样本库：默认学习案例「客服工单」（SQLite 可直接执行）
-- 说明：非课程业务锚点；可按同构字段替换为订单/线索/审批等
-- 业务含义：模拟「待处理事项」主表 + 主体表，供第1—2周 SQL 练习使用

DROP TABLE IF EXISTS tickets;
DROP TABLE IF EXISTS customers;

CREATE TABLE customers (
  customer_id TEXT PRIMARY KEY, -- 客户唯一编号（主键：能唯一标识一行的字段）
  customer_name TEXT NOT NULL,  -- 客户姓名
  vip_level TEXT NOT NULL,      -- 会员等级：普通/黄金/白金
  city TEXT NOT NULL,           -- 城市
  phone_masked TEXT NOT NULL    -- 脱敏手机号
);

CREATE TABLE tickets (
  ticket_id TEXT PRIMARY KEY,           -- 工单唯一编号
  customer_id TEXT NOT NULL,            -- 关联客户（外键：指向另一张表主键的字段）
  created_at TEXT NOT NULL,             -- 创建时间
  channel TEXT NOT NULL,                -- 渠道：app/hotline/wechat
  category TEXT NOT NULL,               -- 问题分类
  priority TEXT NOT NULL,               -- 优先级：高/中/低
  status TEXT NOT NULL,                 -- 状态
  subject TEXT NOT NULL,                -- 标题
  content TEXT NOT NULL,                -- 正文
  FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

